"""The gateway's shipped allowlist: which device signals publish, and how.

Deliberately one entry. The fuel level sensor is what the Fuel Loss Draft's
demonstration is about, and v4 section 11.2 makes the mapping explicit rather
than a gateway that forwards whatever a device produced. The PV, BMS, generator,
meter and policy extension is T026's; operational fuel delivery and dip records
are a separate source family and are T030's.

The generator controller's hourly power signal is generated by the transform and
is visible in the Lab, and it publishes NOTHING here: it is not on the list. That
is the allowlist working, and the stage inspector says which signals it covers.

## Versioned, and frozen into every stage

`mapping_version` moves whenever any field below changes, because a stage
records the whole mapping it was staged under and a reader compares versions.
Editing an entry in place without moving the version would give two different
mappings one identity - the thing a version exists to rule out.
"""

from __future__ import annotations

from assetops_contracts.source_envelope import SourceMappingEntry, SourceMappingSet

SIMULATOR_LAB_GATEWAY_MAPPINGS = SourceMappingSet(
    mapping_set_id="simulator-lab-gateway-fuel",
    mapping_version=1,
    # A declared, deterministic delay between a sample and its publication, so
    # the source time and the publication time are two visibly different
    # instants. Buffering, outage and retry timing are T026A's.
    publication_latency_seconds=3,
    entries=(
        SourceMappingEntry(
            device_id="fuel-level-sensor",
            signal_id="fuel-level",
            measurement="STATE_AT_INSTANT",
            unit="L",
            publishes_unavailable=True,
        ),
    ),
)
