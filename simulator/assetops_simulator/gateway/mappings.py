"""The gateway's shipped allowlist: which device signals publish, and how.

Deliberately one entry. The fuel level sensor is what the Fuel Loss Draft's
demonstration is about, and v4 section 11.2 makes the mapping explicit rather
than a gateway that forwards whatever a device produced. The PV, BMS, generator,
meter and policy extension is T026's; operational fuel delivery and dip records
are a separate source family and are T030's.

The generator controller's hourly power signal is generated by the transform and
is visible in the Lab, and it publishes NOTHING here: it is not on the list. That
is the allowlist working, and the stage inspector says which signals it covers.

T025b: the generator controller's typed status reading (publication profile 4)
is likewise generated and visible in the Lab and NOT staged. Envelope schema 1
carries numbers only, so an entry promising it is refused
(`refuse_an_enum_under_schema_1`) rather than omitted or disguised as a
decimal; staging generator status is T026's. This mapping is unchanged.

## Versioned, and frozen into every stage

`mapping_version` moves whenever any field below changes, because a stage
records the whole mapping it was staged under and a reader compares versions.
Editing an entry in place without moving the version would give two different
mappings one identity - the thing a version exists to rule out.
"""

from __future__ import annotations

from dataclasses import dataclass

from assetops_contracts.source_envelope import SourceMappingEntry, SourceMappingSet
from assetops_contracts.source_envelope_v4 import V4_COLD_CHANNEL_MAPPINGS, ChannelMapping

SIMULATOR_LAB_GATEWAY_MAPPINGS = SourceMappingSet(
    mapping_set_id="simulator-lab-gateway-fuel",
    mapping_version=1,
    # A declared, deterministic delay between a sample and its publication, so
    # the source time and the publication time are two visibly different
    # instants. Buffering, outage and retry timing are T026A's.
    publication_latency_seconds=3,
    entries=(
        SourceMappingEntry(
            device_id="fuel-level-sensor",
            signal_id="fuel-level",
            measurement="STATE_AT_INSTANT",
            unit="L",
            publishes_unavailable=True,
        ),
    ),
)


# --- T026: the dispatch-capable mapping, envelope schema 2 -------------------
#
# Publication profile 5's allowlist. Every telemetry path profile 5 declares,
# including the two capability signals (template v3) and generator status as a
# typed member, plus two record families: the Foundation policy the controller
# runs under, and operator override commands. Record channels are declared here
# against existing components' devices, not as template signals
# (`D-2026-10-02-template-bump-record`); Site Controls have no device, so the
# gateway publishes them as `site-controller`, with no component.
#
# Profiles 3 and 4 keep the fuel-only schema-1 mapping above, so a Draft frozen
# under either stages exactly what it staged before T026.

#: The members a generator status reading may carry: the lifecycle the
#: mini-grid model declares. A member outside this list is refused at the stage.
GENERATOR_STATUS_MEMBERS = ("STOPPED", "STARTING", "RUNNING", "FAILED")


def _reading(device_id, signal_id, measurement, unit, members=None):
    return SourceMappingEntry(
        device_id=device_id,
        signal_id=signal_id,
        measurement=measurement,
        unit=unit,
        publishes_unavailable=True,
        family="MEASUREMENT",
        members=members,
        envelope_schema_version=2,
    )


def _record(device_id, signal_id, family, unit):
    return SourceMappingEntry(
        device_id=device_id,
        signal_id=signal_id,
        measurement=None,
        unit=unit,
        publishes_unavailable=False,
        family=family,
        envelope_schema_version=2,
    )


