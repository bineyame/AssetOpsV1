"""EV-HB (D-E5.48 card EV-HB): the generated EV story days on the declared charging hours 08:00-16:00.

Host side of `backend/tests/test_evhb_ev_window.py` (backend tests may not import the simulator; the host does,
`host/ev_publication.py`). Each EV story day of the v4 list is generated by the producer's own scenario helpers
(`tools/demo_combined_ev.py` `story_definition`) and the host's EV execution, then compared with the registered
one-hour day: a status heartbeat at every minute, no duplicate instant, the sessions, fault and energy byte for byte,
and `charging_kwh` grading COMPLETE on the 8 declared hours where the hour graded LOW.
"""

